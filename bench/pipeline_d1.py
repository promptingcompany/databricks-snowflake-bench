"""D1 runner: the Phase 2 pipeline as a notebook task on Databricks SERVERLESS JOBS compute.
Why a notebook: SQL tasks in a job run on SQL warehouses; Jobs serverless compute needs a notebook
or Python task. The notebook runs the SAME rendered SQL as bench.pipeline (same steps, same checksums).
Usage: python -m bench.pipeline_d1 --scale 10|100 [--runs 3] [--submit] [--yes]
  default      : PREVIEW ONLY. Writes results/d1_notebook_preview.py. Touches nothing remote.
  --submit     : uploads the notebook to the workspace and submits one-time job runs (spends money).
  --yes        : additionally required at scale 100.
Each run is a separate job submission, so each pays its own serverless start-up.
Cost: NOT computed from a rate. Reconcile from system.billing.usage by job run id (has a lag);
this script records run ids and timings (setup/execution/cleanup) for that."""
import os, sys, json, time, base64, pathlib, datetime, yaml
from dotenv import load_dotenv
from .pipeline import STEPS, CHECKS, render, opt

NB_TEMPLATE = '''# Databricks notebook source
# Generated by bench.pipeline_d1. Runs the Phase 2 pipeline SQL on serverless jobs compute.
import json, time
CATALOG, SRC_SCHEMA, OUT_SCHEMA = {catalog!r}, {src!r}, {out!r}
STEPS = {steps}
CHECKS = {checks}
spark.sql(f"USE CATALOG {{CATALOG}}")
spark.sql(f"USE SCHEMA {{SRC_SCHEMA}}")
spark.sql(f"CREATE SCHEMA {{CATALOG}}.{{OUT_SCHEMA}}")
spark.sql(f"USE SCHEMA {{SRC_SCHEMA}}")
res, ok = [], True
for step, f, sql in STEPS:
    t = time.perf_counter()
    try:
        spark.sql(sql).collect()
        res.append({{"step": step, "file": f, "ok": True, "seconds": time.perf_counter() - t}})
    except Exception as ex:
        res.append({{"step": step, "file": f, "ok": False, "error": str(ex)[:400]}})
        ok = False
        break
cs = {{}}
if ok:
    for tbl, exprs in CHECKS.items():
        row = spark.sql(f"SELECT {{', '.join(exprs)}} FROM {{CATALOG}}.{{OUT_SCHEMA}}.{{tbl}}").collect()[0]
        cs[tbl] = [None if v is None else f"{{round(float(v), 2):.2f}}" for v in row]
spark.sql(f"DROP SCHEMA IF EXISTS {{CATALOG}}.{{OUT_SCHEMA}} CASCADE")
dbutils.notebook.exit(json.dumps({{"steps": res, "checksums": cs, "ok": ok}}))
'''

def build_notebook(cfg, scale, tag):
    out = f"{cfg['catalog']}.{tag}"
    steps = [(s, f, render(f, out, "databricks")) for s, f in STEPS]
    return NB_TEMPLATE.format(catalog=cfg["catalog"], src=f"tpcds_sf{scale}" + os.environ.get("BENCH_SRC_SUFFIX", "").lower(), out=tag,
                              steps=repr(steps), checks=repr(CHECKS))

def main():
    load_dotenv(os.path.join(os.getcwd(), ".env"))
    scale = opt("--scale")
    if scale not in ("10", "100", "1000"): sys.exit(__doc__)
    cfg = yaml.safe_load(open("config.yaml"))["databricks"]
    runs = int(opt("--runs") or 3)
    stamp = time.strftime("%Y%m%d%H%M%S")
    if "--submit" not in sys.argv:
        p = pathlib.Path("results/d1_notebook_preview.py")
        p.write_text(build_notebook(cfg, scale, f"out_d1_{stamp}_1"))
        print(f"PREVIEW ONLY. Notebook source written to {p}. Nothing was uploaded or run.")
        return
    if scale in ("100", "1000") and "--yes" not in sys.argv:
        sys.exit("Scale 100 spends real money. Re-run with --yes after reviewing the estimate.")
    from databricks.sdk import WorkspaceClient
    from databricks.sdk.service.jobs import SubmitTask, NotebookTask
    from databricks.sdk.service.workspace import ImportFormat, Language
    w = WorkspaceClient(host="https://" + os.environ["DATABRICKS_HOST"], token=os.environ["DATABRICKS_TOKEN"], auth_type="pat")
    me = w.current_user.me().user_name
    folder = f"/Users/{me}/bench_d1"
    w.workspace.mkdirs(folder)
    path = pathlib.Path("results") / f"pipeline-D1-sf{scale}-{stamp}.jsonl"
    for run in range(1, runs + 1):
        tag = f"out_d1_{stamp}_{run}"
        nb = f"{folder}/pipeline_run_{stamp}_{run}"
        w.workspace.import_(nb, content=base64.b64encode(build_notebook(cfg, scale, tag).encode()).decode(),
                            format=ImportFormat.SOURCE, language=Language.PYTHON, overwrite=True)
        # No cluster spec on a notebook task => serverless jobs compute.
        # STANDARD serverless mode chosen by the user (cheaper, slower start). The SDK's submit() has no argument
        # for it, so call the REST endpoint directly and confirm the setting from the run details afterwards.
        sub = w.api_client.do("POST", "/api/2.1/jobs/runs/submit", body={
            "run_name": f"bench-d1-{stamp}-{run}", "performance_target": "STANDARD",
            "tasks": [{"task_key": "pipeline", "notebook_task": {"notebook_path": nb}}]})
        w.jobs.wait_get_run_job_terminated_or_skipped(sub["run_id"], timeout=datetime.timedelta(hours=4))
        raw = w.api_client.do("GET", "/api/2.1/jobs/runs/get", query={"run_id": sub["run_id"]})
        r = w.jobs.get_run(sub["run_id"])
        task = r.tasks[0]
        eff = (raw.get("tasks") or [{}])[0].get("effective_performance_target") or raw.get("effective_performance_target") or "NOT REPORTED"
        print("run", sub["run_id"], "effective_performance_target:", eff, "| state:", raw.get("state", {}).get("result_state"), flush=True)
        out = json.loads(w.jobs.get_run_output(task.run_id).notebook_output.result)
        meta = {"option": "D1", "engine": "databricks", "scale": scale, "run": run, "run_id": task.run_id, "job_run_id": sub["run_id"],
                "setup_ms": task.setup_duration, "exec_ms": task.execution_duration, "cleanup_ms": task.cleanup_duration,
                "performance_target": eff}
        for s in out["steps"]:
            open(path, "a").write(json.dumps({**meta, **s, "cold": run == 1}) + "\n")
            print("D1", run, s["file"], s.get("seconds") or s.get("error"), flush=True)
        open(path, "a").write(json.dumps({**meta, "step": "TOTAL", "ok": out["ok"],
                                          "seconds": sum(s.get("seconds", 0) for s in out["steps"]),
                                          "checksums": out["checksums"]}) + "\n")
        w.workspace.delete(nb)
    print("wrote", path)

if __name__ == "__main__": main()
