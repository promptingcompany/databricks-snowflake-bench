"""D1 runner for the CDC pipeline: the same steps as bench.cdc, as a notebook task on Databricks SERVERLESS JOBS compute
(standard mode, set through the REST submit call). Each run is its own job submission so each pays its own start-up, and its
billing is attributable by top-level job run id (record field job_run_id).
Usage: python -m bench.cdc_d1 --scale 10|100 [--runs 1] [--batches 10] [--submit] [--yes]
 default  : PREVIEW ONLY. Writes results/cdc_d1_notebook_preview.py. Nothing is uploaded or run.
 --submit : uploads the notebook to /Users/<you>/bench_d1 and submits one-time job runs (spends money). SF100 also needs --yes.
Step timings come from inside the notebook (client of spark.sql), not from query history."""
import os, sys, json, time, base64, pathlib, datetime, yaml
from dotenv import load_dotenv
from .cdc import T1_SUMS, T2_SUMS
from .pipeline import render, opt

SENT = {"LO": 111111111, "HI": 222222222, "OFF": 333333333}  # sentinels swapped for real values inside the notebook
NAMES = ("cdc_changes", "cdc_merge", "cdc_refresh_delete", "cdc_refresh_insert", "cdc_drop")

NB = '''# Databricks notebook source
# Generated by bench.cdc_d1. CDC pipeline on serverless jobs compute.
import json, time
CATALOG, SRC, OUT, NBATCH = {catalog!r}, {src!r}, {out!r}, {n}
BASE = {base}
BATCH = {batch}
SENT = {sent}
CHK = {chk}
def sub(sql, lo=0, hi=0, off=0):
    return sql.replace(str(SENT["LO"]), str(lo)).replace(str(SENT["HI"]), str(hi)).replace(str(SENT["OFF"]), str(off))
spark.sql(f"USE CATALOG {{CATALOG}}")
spark.sql(f"USE SCHEMA {{SRC}}")
spark.sql(f"CREATE SCHEMA {{CATALOG}}.{{OUT}}")
spark.sql(f"USE SCHEMA {{SRC}}")
recs, ok = [], True
def step(name, sql, batch=None):
    global ok
    t = time.perf_counter()
    try:
        spark.sql(sql).collect(); recs.append({{"step": name, "batch": batch, "ok": True, "seconds": time.perf_counter() - t}})
    except Exception as ex:
        recs.append({{"step": name, "batch": batch, "ok": False, "error": str(ex)[:400]}}); ok = False
def check(batch):
    r1 = spark.sql(f"SELECT {{CHK['t1']}} FROM {{CATALOG}}.{{OUT}}.t1_wide").collect()[0]
    r2 = spark.sql(f"SELECT {{CHK['t2']}} FROM {{CATALOG}}.{{OUT}}.t2_daily").collect()[0]
    f = lambda row: [None if v is None else f"{{round(float(v), 2):.2f}}" for v in row]
    t1, t2 = f(r1), f(r2)
    recs.append({{"step": "CHECK", "batch": batch, "ok": True, "checksums": {{"t1": t1, "t2": t2, "t2_matches_t1": t2[1] == t1[1]}}}})
for nm, sql in BASE:
    if ok: step(nm, sql)
if ok:
    check(0)
    base_sk = int(spark.sql("SELECT d_date_sk FROM date_dim WHERE d_date = CAST('2001-01-01' AS DATE)").collect()[0][0])
    for b in range(1, NBATCH + 1):
        lo, hi = base_sk + (b - 1) * 30, base_sk + b * 30 - 1
        for nm, sql in BATCH:
            if ok: step(f"B{{b}}_{{nm}}", sub(sql, lo, hi, 1000000000 * b), b)
        if ok and b in (1, 5, 10): check(b)
spark.sql(f"DROP SCHEMA IF EXISTS {{CATALOG}}.{{OUT}} CASCADE")
dbutils.notebook.exit(json.dumps({{"recs": recs, "ok": ok}}))
'''

def build(cfg, scale, tag, n):
    out = f"{cfg['catalog']}.{tag}"
    base = [("BASE_T1", render("t1_wide", out, "databricks")), ("BASE_T2", render("t2_daily", out, "databricks"))]
    # render_cdc substitutes OFF as 1e9*b, so render here with sentinel values that the notebook swaps at run time
    batch = []
    for nm in NAMES:
        import pathlib as _p, sqlglot
        sql = _p.Path("pipeline_cdc", nm + ".sql").read_text().replace("{OUT}", out)
        sql = sql.replace("{LO}", str(SENT["LO"])).replace("{HI}", str(SENT["HI"])).replace("{OFF}", str(SENT["OFF"]))
        batch.append((nm, sqlglot.transpile(sql, read="duckdb", write="databricks")[0]))
    return NB.format(catalog=cfg["catalog"], src=f"tpcds_sf{scale}" + os.environ.get("BENCH_SRC_SUFFIX", "").lower(), out=tag, n=n, base=repr(base), batch=repr(batch),
                     sent=repr(SENT), chk=repr({"t1": ", ".join(T1_SUMS), "t2": ", ".join(T2_SUMS)}))

def main():
    load_dotenv(os.path.join(os.getcwd(), ".env"))
    scale = opt("--scale")
    if scale not in ("10", "100", "1000"): sys.exit(__doc__)
    cfg = yaml.safe_load(open("config.yaml"))["databricks"]
    n = int(opt("--batches") or 10); runs = int(opt("--runs") or 1)
    stamp = time.strftime("%Y%m%d%H%M%S")
    if "--submit" not in sys.argv:
        p = pathlib.Path("results/cdc_d1_notebook_preview.py"); p.write_text(build(cfg, scale, f"out_cdc_d1_{stamp}_1", n))
        print(f"PREVIEW ONLY. Notebook source written to {p}. Nothing was uploaded or run."); return
    if scale in ("100", "1000") and "--yes" not in sys.argv: sys.exit("Scale 100 spends real money. Re-run with --yes after the estimate.")
    from databricks.sdk import WorkspaceClient
    from databricks.sdk.service.workspace import ImportFormat, Language
    w = WorkspaceClient(host="https://" + os.environ["DATABRICKS_HOST"], token=os.environ["DATABRICKS_TOKEN"], auth_type="pat")
    folder = f"/Users/{w.current_user.me().user_name}/bench_d1"; w.workspace.mkdirs(folder)
    path = pathlib.Path("results") / f"cdc-D1-sf{scale}-{stamp}.jsonl"
    for run in range(1, runs + 1):
        tag = f"out_cdc_d1_{stamp}_{run}"; nb = f"{folder}/cdc_run_{stamp}_{run}"
        w.workspace.import_(nb, content=base64.b64encode(build(cfg, scale, tag, n).encode()).decode(),
                            format=ImportFormat.SOURCE, language=Language.PYTHON, overwrite=True)
        sub = w.api_client.do("POST", "/api/2.1/jobs/runs/submit", body={"run_name": f"bench-cdc-d1-{stamp}-{run}",
              "performance_target": "STANDARD", "tasks": [{"task_key": "cdc", "notebook_task": {"notebook_path": nb}}]})
        w.jobs.wait_get_run_job_terminated_or_skipped(sub["run_id"], timeout=datetime.timedelta(hours=4))
        raw = w.api_client.do("GET", "/api/2.1/jobs/runs/get", query={"run_id": sub["run_id"]})
        task = raw["tasks"][0]
        out = json.loads(w.jobs.get_run_output(task["run_id"]).notebook_output.result)
        meta = {"option": "D1", "engine": "databricks", "scale": scale, "run": run, "job_run_id": sub["run_id"], "task_run_id": task["run_id"],
                "setup_ms": task.get("setup_duration"), "exec_ms": task.get("execution_duration"), "performance_target": task.get("effective_performance_target", "NOT REPORTED")}
        for r in out["recs"]: open(path, "a").write(json.dumps({**meta, **r}) + "\n")
        print("D1 run", run, "job_run_id", sub["run_id"], "mode", meta["performance_target"], "ok", out["ok"], flush=True)
        w.workspace.delete(nb)
    print("wrote", path)

if __name__ == "__main__": main()
