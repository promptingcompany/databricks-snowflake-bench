"""D1 runner for the DI-style ETL: same statements as bench.di_etl (Databricks dialect), run as a notebook task on
Databricks SERVERLESS JOBS compute, standard mode (set through the REST submit call). One job submission per run, so each run
pays its own start-up and its billing is attributable by top-level job run id (field job_run_id).
Usage: python -m bench.di_d1 --sf 1|10|100 [--runs 1] [--submit] [--yes (sf >= 100)]
 default  : PREVIEW ONLY. Writes results/di_d1_notebook_preview.py. Nothing is uploaded or run.
 --submit : uploads the notebook to /Users/<you>/bench_d1 and submits one-time job runs (spends money).
Step timings are measured inside the notebook (spark.sql), not from query history."""
import os, sys, json, time, base64, pathlib, yaml
from dotenv import load_dotenv
from .di_etl import (BATCHES, TRANSFORM, AUDITS, DDL, CHECKS, FILE_OF, CSV_SCHEMAS, ingest_databricks, render)
from .pipeline import opt

NB = '''# Databricks notebook source
# Generated by bench.di_d1. DI-style ETL on serverless jobs compute.
import json, time
CATALOG, OUT = {catalog!r}, {out!r}
DDL = {ddl}
PLAN = {plan}
CHK = {chk}
recs, ok = [], True
def step(name, sql, phase, b):
    global ok
    t = time.perf_counter()
    try:
        spark.sql(sql).collect(); recs.append({{"step": name, "phase": phase, "batch": b, "ok": True, "seconds": time.perf_counter() - t}})
    except Exception as ex:
        recs.append({{"step": name, "phase": phase, "batch": b, "ok": False, "error": str(ex)[:500]}}); ok = False
def one(sql): return spark.sql(sql).collect()[0]
spark.sql(f"CREATE SCHEMA {{CATALOG}}.{{OUT}}")
for nm, sql in DDL:
    if ok: step(nm, sql, "INIT", 0)
for b in sorted(PLAN):
    if not ok: break
    p = PLAN[b]
    for nm, sql in p["ingest"]:
        if ok: step(nm, sql, "INGEST", b)
    if not ok: break
    for tbl, exp in p["reconcile"]:
        got = int(one(f"SELECT COUNT(*) FROM {{CATALOG}}.{{OUT}}.{{tbl}}")[0])
        recs.append({{"step": "RECONCILE", "batch": b, "table": tbl, "got": got, "expected": exp, "ok": got == exp}})
    for nm, sql in p["transform"]:
        if ok: step(nm, sql, "TRANSFORM", b)
    if not ok: break
    for nm, sql in p["audit"]:
        recs.append({{"step": "AUDIT", "name": nm, "batch": b, "violations": int(one(sql)[0])}})
    cs = {{}}
    for t, exprs in CHK.items():
        row = one(f"SELECT {{', '.join(exprs)}} FROM {{CATALOG}}.{{OUT}}.{{t}}")
        cs[t] = [None if v is None else f"{{round(float(v), 2):.2f}}" for v in row]
    recs.append({{"step": "CHECK", "batch": b, "ok": True, "checksums": cs}})
spark.sql(f"DROP SCHEMA IF EXISTS {{CATALOG}}.{{OUT}} CASCADE")
dbutils.notebook.exit(json.dumps({{"recs": recs, "ok": ok}}))
'''

def build(cfg, sf, tag):
    out = f"{cfg['catalog']}.{tag}"
    report = json.load(open(f"data/di/sf{sf}/di_report.json"))
    ddl = [(n, render(n, out, "databricks")) for n in DDL]
    plan = {}
    for b in BATCHES:
        files = report["batches"][str(b)]["files"]
        rec = [(t, files[fn]["rows"]) for t, fn in {**FILE_OF, "stg_customer": "Customer.json", "stg_security": "Security.dat"}.items()
               if fn in files and (b == 1 or t.startswith("stg_"))]
        plan[b] = {"ingest": ingest_databricks(b, out, sf), "reconcile": rec,
                   "transform": [(n, render(n, out, "databricks", b)) for n in TRANSFORM],
                   "audit": [(n, render(n, out, "databricks")) for n in AUDITS]}
    return NB.format(catalog=cfg["catalog"], out=tag, ddl=repr(ddl), plan=repr(plan), chk=repr(CHECKS))

def main():
    load_dotenv(os.path.join(os.getcwd(), ".env"))
    sf = opt("--sf")
    if sf not in ("1", "10", "100"): sys.exit(__doc__)
    cfg = yaml.safe_load(open("config.yaml"))["databricks"]; runs = int(opt("--runs") or 1)
    stamp = time.strftime("%Y%m%d%H%M%S")
    if "--submit" not in sys.argv:
        p = pathlib.Path("results/di_d1_notebook_preview.py"); p.write_text(build(cfg, sf, f"out_di_d1_{stamp}_1"))
        print(f"PREVIEW ONLY. Notebook source written to {p}. Nothing was uploaded or run."); return
    if float(sf) >= 100 and "--yes" not in sys.argv: sys.exit("This SF spends real money; re-run with --yes after the estimate.")
    from databricks.sdk import WorkspaceClient
    from databricks.sdk.service.workspace import ImportFormat, Language
    w = WorkspaceClient(host="https://" + os.environ["DATABRICKS_HOST"], token=os.environ["DATABRICKS_TOKEN"], auth_type="pat")
    folder = f"/Users/{w.current_user.me().user_name}/bench_d1"; w.workspace.mkdirs(folder)
    path = pathlib.Path("results") / f"di-D1-sf{sf}-{stamp}.jsonl"
    for run in range(1, runs + 1):
        tag = f"out_di_d1_{stamp}_{run}"; nb = f"{folder}/di_run_{stamp}_{run}"
        w.workspace.import_(nb, content=base64.b64encode(build(cfg, sf, tag).encode()).decode(), format=ImportFormat.SOURCE, language=Language.PYTHON, overwrite=True)
        sub = w.api_client.do("POST", "/api/2.1/jobs/runs/submit", body={"run_name": f"bench-di-d1-{stamp}-{run}", "performance_target": "STANDARD",
              "tasks": [{"task_key": "di", "notebook_task": {"notebook_path": nb}}]})
        w.jobs.wait_get_run_job_terminated_or_skipped(sub["run_id"])
        raw = w.api_client.do("GET", "/api/2.1/jobs/runs/get", query={"run_id": sub["run_id"]}); task = raw["tasks"][0]
        out = json.loads(w.jobs.get_run_output(task["run_id"]).notebook_output.result)
        meta = {"option": "D1", "engine": "databricks", "sf": sf, "run": run, "job_run_id": sub["run_id"], "task_run_id": task["run_id"],
                "setup_ms": task.get("setup_duration"), "exec_ms": task.get("execution_duration"), "performance_target": task.get("effective_performance_target", "NOT REPORTED")}
        for r in out["recs"]: open(path, "a").write(json.dumps({**meta, **r}) + "\n")
        print("D1 run", run, "job_run_id", sub["run_id"], "mode", meta["performance_target"], "ok", out["ok"], flush=True)
        w.workspace.delete(nb)
    print("wrote", path)

if __name__ == "__main__": main()
